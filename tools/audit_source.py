"""Fail closed on unintended repository content. Does not certify legal provenance."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT=Path(__file__).resolve().parents[1]
PREFIXES=('launcher/','recomp/','libgc/','runtime/','port/','tests/','tools/','cmake/','data/','docs/','licenses/','.github/')
ROOT_FILES={'.gitignore','.gitattributes','CMakeLists.txt','CMakePresets.json','README.md','README-INTEGRATION.md','LICENSE.txt','THIRD-PARTY-NOTICES.txt'}
SUFFIXES={'.cpp','.h','.hpp','.inc','.cmake','.py','.ps1','.cmd','.rc','.manifest','.txt','.md','.json','.yml','.yaml','.sym','.ttf','.sh'}
FORBIDDEN_PARTS={'private','generated','recompiled','game_data','saves','states','runs','vendor','build-kit','node_modules','__pycache__'}
FORBIDDEN_EXT={'.iso','.gcm','.rvz','.wia','.gcz','.ciso','.dol','.bik','.raw','.ram','.state','.coop','.exe','.dll','.o','.obj','.a','.lib','.pdb','.mp4','.bmp','.zip','.7z','.bin'}

def inspect(name,data):
    p=Path(name);issues=[]
    if p.is_absolute() or '..' in p.parts:issues.append('unsafe path')
    metadata=name in {'data/kit/kit.ini','data/kit/kit-linux.ini.in','data/pgo/runtime.proftext'}
    if name not in ROOT_FILES and not metadata and (not name.startswith(PREFIXES) or (p.suffix not in SUFFIXES and p.name!='CMakeLists.txt')):issues.append('outside source allowlist')
    if any(part in FORBIDDEN_PARTS or part.startswith('build-') for part in p.parts):issues.append('private/generated/build directory')
    if p.name.endswith('.ini.multiplayer'):issues.append('personal multiplayer settings')
    if p.suffix.lower() in FORBIDDEN_EXT:issues.append('excluded artifact type')
    # This atlas is generated from the included OFL font by make_prompt_icons.py.
    # Keep an exact reviewed digest instead of allowing arbitrary large source blobs.
    reviewed_atlas=(name=='runtime/src/gx/prompt_icons.inc' and hashlib.sha256(data).hexdigest()==
                    '248653d6472628f20d792e27b457fd2acf098e09df2152de881dfb437fe2ec1f')
    if len(data)>2*1024*1024 and not reviewed_atlas:issues.append('oversized source file')
    if p.suffix=='.ttf':
        if p.parent.as_posix()!='launcher/fonts' or p.name not in ('EricaOne-Regular.ttf','Outfit-Regular.ttf','Outfit-Bold.ttf'):issues.append('unreviewed font asset')
        return issues
    try:text=data.decode('utf-8-sig')
    except UnicodeDecodeError:return issues+['non-UTF8 source']
    checks={
      'private key':r'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----',
      'credential':r'\b(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,}|AKIA[A-Z0-9]{16})\b',
      'machine-specific path':r'[A-Za-z]:[/\\]Users[/\\][^\s"\x27]+',
      'generated game function body':r'^\s*void f_80[0-9A-Fa-f]{6}[^\n]*\(PPCContext&[^\n]*\)\s*\{',
      'generated translation header':r'^// Generated by ssne-recomp\. Do not edit',
    }
    for label,pattern in checks.items():
        if re.search(pattern,text,re.M):issues.append(label)
    return issues

def audit(root=ROOT):
    names=subprocess.check_output(['git','ls-files','-z'],cwd=root).decode().split('\0')
    names=[n for n in names if n]
    if not names:raise RuntimeError('Empty index; stage intended sources before auditing')
    failures=[];total=0
    for name in names:
        path=root/name
        if path.is_symlink():failures.append({'file':name,'issues':['symlink']});continue
        # Inspect the canonical staged bytes: exactly what will be committed.
        data=subprocess.check_output(['git','show',':'+name],cwd=root);total+=len(data)
        found=inspect(name,data)
        if found:failures.append({'file':name,'issues':found})
    return {'files':len(names),'bytes':total,'violations':failures,'passed':not failures}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--report',type=Path);args=parser.parse_args()
    result=audit()
    if args.report:
        args.report.parent.mkdir(parents=True,exist_ok=True)
        args.report.write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(result,indent=2))
    raise SystemExit(0 if result['passed'] else 1)
